using AutoMapper;
using Hotel.Core.DTOs.Auth;
using Hotel.Core.DTOs.Hotels;
using Hotel.Core.DTOs.Inquiries;
using Hotel.Core.DTOs.Payments;
using Hotel.Core.DTOs.Rooms;
using Hotel.Core.Entities;
using HotelEntity = Hotel.Core.Entities.Hotel;

namespace Hotel.Service.Mapping;

public class MappingProfile : Profile
{
    public MappingProfile()
    {
        // Hotel
        CreateMap<CreateHotelDto, HotelEntity>();
        CreateMap<UpdateHotelDto, HotelEntity>();
        CreateMap<HotelEntity, HotelResponseDto>()
            .ForMember(dest => dest.ImageUrls, opt => opt.MapFrom(
                src => src.Images.OrderBy(i => i.DisplayOrder).Select(i => i.Url)));

        // Room
        CreateMap<CreateRoomDto, Room>();
        CreateMap<UpdateRoomDto, Room>();
        CreateMap<Room, RoomResponseDto>()
            .ForMember(dest => dest.ImageUrls, opt => opt.MapFrom(
                src => src.Images.OrderBy(i => i.DisplayOrder).Select(i => i.Url)));

        // Payment
        // UserId/Amount/IsPaid are determined by the service (not supplied by the client)
        CreateMap<CreatePaymentDto, Payment>()
            .ForMember(dest => dest.UserId, opt => opt.Ignore())
            .ForMember(dest => dest.Amount, opt => opt.Ignore())
            .ForMember(dest => dest.IsPaid, opt => opt.Ignore());
        CreateMap<Payment, PaymentResponseDto>();

        // Auth / User
        // PasswordHash is hashed separately; Role defaults server-side
        CreateMap<RegisterDto, User>()
            .ForMember(dest => dest.PasswordHash, opt => opt.Ignore())
            .ForMember(dest => dest.Role, opt => opt.Ignore());
        // Token is generated by the auth service after mapping
        CreateMap<User, AuthResponseDto>()
            .ForMember(dest => dest.Token, opt => opt.Ignore());

        // Inquiry
        // UserId/CreatedAt/ResponseText/RespondedAt are determined by the service, not the client
        CreateMap<CreateInquiryDto, Inquiry>()
            .ForMember(dest => dest.UserId, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedAt, opt => opt.Ignore())
            .ForMember(dest => dest.ResponseText, opt => opt.Ignore())
            .ForMember(dest => dest.RespondedAt, opt => opt.Ignore());

        CreateMap<Inquiry, InquiryResponseDto>()
            .ForMember(dest => dest.HotelName, opt => opt.MapFrom(src => src.Hotel.Name))
            .ForMember(dest => dest.Status, opt => opt.MapFrom(src => src.ResponseText == null ? "AwaitingResponse" : "Responded"));

        CreateMap<Inquiry, AdminInquiryResponseDto>()
            .ForMember(dest => dest.HotelName, opt => opt.MapFrom(src => src.Hotel.Name))
            .ForMember(dest => dest.UserName, opt => opt.MapFrom(src => src.User.Name))
            .ForMember(dest => dest.UserEmail, opt => opt.MapFrom(src => src.User.Email))
            .ForMember(dest => dest.Status, opt => opt.MapFrom(src => src.ResponseText == null ? "AwaitingResponse" : "Responded"));
    }
}
